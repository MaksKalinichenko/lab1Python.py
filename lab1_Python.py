# Програма для аналізу температурних показів за день

print("=== Аналіз температурних показів за день ===")
print("Введіть до 24 значень температур (через пробіл):")

# Введення температур користувачем
### TODO: організувати ввод послідовності одним рядком, дані очистити від зайвих пробілів та розділити покази у рядку на список по пробілам між ними
raw_temps = input("Температури: ").strip()
temp_strings = raw_temps.split()
# Перевірка кількості значень
### TODO: Перевірити, що було введено не пустий рядок (0 показів) та що загальна кількість показів не перевищує 24, інакше забезпечити вихід з програми
if len(temp_strings) == 0:
    print("Помилка: не введено жодного значення.")
    exit()

if len(temp_strings) > 24:
    print("Помилка: кількість значень перевищує 24.")
    exit()
# Створення та наповнення списку для числових значень показів температур
### TODO: Створення списку та перевірка коректності кожного числа: 
### а) має бути таким, щоб його можна було перетворити на float 
###  б) входить у діапазон допустимих температур (-40..40)
temperatures = []

for item in temp_strings:
    item = item.replace(",", ".")
    try:
        value = float(item)
    except ValueError:
        print(f"Помилка: '{item}' не є числом.")
        exit()

    if value < -40 or value > 40:
        print(f"Помилка: значення {value} поза діапазоном -40..40.")
        exit()

    temperatures.append(value)
# Перевірка, чи додались у список хоч якісь дані (список с числовими показами містить значення), інакше завершити програму
### TODO: перевірити, що список не пустий і містить хоча б два значення
if len(temperatures) < 2:
    print("Помилка: потрібно щонайменше два вимірювання.")
    exit()
# Введення часових міток
print("\nВведіть часові мітки для кожного показу (у форматі 'година:хвилина') через пробіл:")
### TODO: організувати ввод послідовності одним рядком, дані очистити від зайвих пробілів та розділити покази у рядку на список по пробілам між ними
raw_times = input("Мітки часу: ").strip()
time_strings = raw_times.split()
# Перевірка формату часу
### TODO: перевірити, що формат міток відповідає заданому ("Година:Хвилина"), не має зайвих символів та значення годин та хвилин - у правильному діапазоні (0-23 та 0-59)
time_labels = []

for item in time_strings:
    parts = item.split(":")
    if len(parts) != 2 or not parts[0].isdigit() or not parts[1].isdigit():
        print(f"Помилка: '{item}' не відповідає формату година:хвилина.")
        exit()

    hours = int(parts[0])
    minutes = int(parts[1])

    if hours < 0 or hours > 23 or minutes < 0 or minutes > 59:
        print(f"Помилка: '{item}' - година має бути 0-23, хвилини 0-59.")
        exit()

    time_labels.append(f"{hours:02d}:{minutes:02d}")

if len(set(time_labels)) != len(time_labels):
    print("Помилка: часові мітки повторюються.")
    exit()
# Перевірка кількості міток
### TODO: перевірити, що кількість показників температури та кількість міток збігається, інакше завершити програму
if len(time_labels) != len(temperatures):
    print("Помилка: кількість міток часу не збігається з кількістю температур.")
    exit()
# Створення словника {час: температура, час: температура, ...}
### TODO: створити та наповнити словник
data = {}
for i in range(len(time_labels)):
    data[time_labels[i]] = temperatures[i]

# === Обчислення характеристик через словник з даними ===
### TODO: зробити розрахунок статистичних параметрів (середнє значення, мінімум, максимум, кількість позитивних та негативних температур, різкі зміни) по даним зі словника
### а) виділити значення та ключі зі словника
### б) розрахувати середнє значення
### в) розрахувати мінімум та максимум
### г) розрахувати кількість позитивних та негативних температур
### д) зробити виявлення різких змін: зробити список, в якому зберігати кортеж-діапазон часових міток, між якими стався різкий перепад температур (>7 градусів), та різниця температур (час1, час2, різниця)
# а) ключі та значення зі словника
times = list(data.keys())
values = list(data.values())

# б) середнє
total = len(values)
average = sum(values) / total

# в) мінімум і максимум
max_temp = max(values)
min_temp = min(values)

# г) додатні та від'ємні (нуль не рахується ні туди, ні туди)
positive_count = 0
negative_count = 0
for t in values:
    if t > 0:
        positive_count += 1
    elif t < 0:
        negative_count += 1

# д) різкі зміни: список кортежів (час1, час2, різниця)
sharp_changes = []
for i in range(1, total):
    diff = round(abs(values[i] - values[i - 1]), 2)
    if diff > 7:
        sharp_changes.append((times[i - 1], times[i], diff))
# === Виведення результатів ===
print("\n=== РЕЗУЛЬТАТ АНАЛІЗУ ===")
print("Температурні дані (час → температура):")
### TODO: вивести усі покази у форматі "часова мітка" - "значення температури" зі словника
for time_label, temp in data.items():
    print(f"   {time_label} → {temp:6.1f} °C")
### TODO: вивести отримані числові значення статистичних показників
print()
print(f"Загальна кількість вимірювань: {total}")
print(f"Середня температура: {average:.2f} °C")
print(f"Максимальна температура: {max_temp} °C")
print(f"Мінімальна температура: {min_temp} °C")
print(f"Кількість додатних температур: {positive_count}")
print(f"Кількість від’ємних температур: {negative_count}")
# Виведення різких змін
### TODO: за утвореним списком з кортежів (час1, час2, різниця) вивести повідомлення про різкі зміни
if sharp_changes:
    print("\n[!] Виявлено різкі зміни температури (> 7°):")
    for t1, t2, diff in sharp_changes:
        print(f"  між {t1} та {t2}: зміна на {diff}°C")
else:
    print("\nРізких змін температури не виявлено.")
print("\n=== Кінець аналізу ===")